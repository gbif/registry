-- Workflow orchestrator (flow-orchestrator) tables.
--
-- Written only by flow-orchestrator; registry reads them. domain lives only on the aggregate root
-- workflow_execution; all other rows reach it through their foreign keys.
--
-- Portable SQL: must also run on H2 in PostgreSQL mode, which flow-orchestrator uses in its tests
-- (flow-orchestrator-app/src/test/resources/schema-h2.sql is a verbatim copy of this file).
-- No enums or partial indexes. JSON is stored as text, except workflow_report.report, which is
-- jsonb so reports can be queried in SQL (H2 accepts the jsonb type in PostgreSQL mode).

CREATE TABLE workflow_execution (
  id              uuid                     NOT NULL PRIMARY KEY,
  domain          varchar(32)              NOT NULL,
  dataset_key     uuid                     NOT NULL,
  attempt         integer                  NOT NULL,
  run             integer                  NOT NULL,
  workflow_name   varchar(128)             NOT NULL,
  definition_hash varchar(64)              NOT NULL,
  parameters      text                     NOT NULL,
  status          varchar(32)              NOT NULL,
  version         integer                  NOT NULL,
  rejected        boolean                  NOT NULL DEFAULT false,
  reason          text,
  created         timestamp with time zone NOT NULL,
  modified        timestamp with time zone NOT NULL,
  finished        timestamp with time zone,
  CONSTRAINT workflow_execution_subject_uq UNIQUE (domain, dataset_key, attempt, run)
);

CREATE INDEX workflow_execution_dataset_idx ON workflow_execution (dataset_key, attempt);

CREATE TABLE step_execution (
  workflow_execution_id uuid                     NOT NULL,
  step_type             varchar(64)              NOT NULL,
  step_order            integer                  NOT NULL,
  status                varchar(32)              NOT NULL,
  current_attempt       integer                  NOT NULL,
  reason                text,
  modified              timestamp with time zone NOT NULL,
  CONSTRAINT step_execution_pk PRIMARY KEY (workflow_execution_id, step_type),
  CONSTRAINT step_execution_workflow_fk FOREIGN KEY (workflow_execution_id)
    REFERENCES workflow_execution (id) ON DELETE CASCADE
);

CREATE TABLE step_attempt (
  workflow_execution_id uuid                     NOT NULL,
  step_type             varchar(64)              NOT NULL,
  attempt_no            integer                  NOT NULL,
  status                varchar(32)              NOT NULL,
  outcome               varchar(16),
  diagnostic            text,
  outputs               text,
  created               timestamp with time zone NOT NULL,
  started               timestamp with time zone,
  finished              timestamp with time zone,
  CONSTRAINT step_attempt_pk PRIMARY KEY (workflow_execution_id, step_type, attempt_no),
  CONSTRAINT step_attempt_step_fk FOREIGN KEY (workflow_execution_id, step_type)
    REFERENCES step_execution (workflow_execution_id, step_type) ON DELETE CASCADE
);

CREATE TABLE workflow_command (
  command_id            uuid                     NOT NULL PRIMARY KEY,
  command_type          varchar(16)              NOT NULL,
  domain                varchar(32),
  dataset_key           uuid                     NOT NULL,
  attempt               integer                  NOT NULL,
  step_type             varchar(64),
  parameters            text                     NOT NULL,
  requested_by          varchar(255)             NOT NULL,
  reason                text,
  requested             timestamp with time zone NOT NULL,
  received              timestamp with time zone NOT NULL,
  workflow_execution_id uuid,
  outcome               varchar(16)              NOT NULL,
  outcome_reason        text,
  CONSTRAINT workflow_command_workflow_fk FOREIGN KEY (workflow_execution_id)
    REFERENCES workflow_execution (id) ON DELETE CASCADE
);

CREATE INDEX workflow_command_dataset_idx ON workflow_command (dataset_key, attempt);

CREATE TABLE outbox_message (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id            uuid                     NOT NULL,
  workflow_execution_id uuid                     NOT NULL,
  step_type             varchar(64),
  step_attempt          integer,
  exchange              varchar(255)             NOT NULL,
  routing_key           varchar(255)             NOT NULL,
  payload               text                     NOT NULL,
  created               timestamp with time zone NOT NULL,
  published             timestamp with time zone,
  publish_attempts      integer                  NOT NULL,
  last_error            text,
  next_attempt          timestamp with time zone,
  CONSTRAINT outbox_message_message_id_uq UNIQUE (message_id),
  CONSTRAINT outbox_message_workflow_fk FOREIGN KEY (workflow_execution_id)
    REFERENCES workflow_execution (id) ON DELETE CASCADE
);

CREATE INDEX outbox_message_unpublished_idx ON outbox_message (published, next_attempt, id);

-- Reports, one per (subject, attempt, report type). Partial reports come from the steps; SUMMARY is
-- built by the orchestrator. dataset_key is the dataset key, or the validation key for validations.
-- No foreign key: the key format is shared with workflow_execution (dataset_key, attempt), and
-- reports outlive a single run.
CREATE TABLE workflow_report (
  dataset_key uuid                     NOT NULL,
  attempt     integer                  NOT NULL,
  report_type varchar(64)              NOT NULL,
  report      jsonb                    NOT NULL,
  comment     text,
  created     timestamp with time zone NOT NULL,
  modified    timestamp with time zone NOT NULL,
  CONSTRAINT workflow_report_pk PRIMARY KEY (dataset_key, attempt, report_type)
);
